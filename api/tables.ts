/**
 * Column map between MariaDB (docs/escuela_futbol_mariadb.sql + db/mariadb/migrations) and the TypeScript models
 * that the domain services use (src/app/core/models, one MockDb array per table). Used by the domain bridge
 * (api/rpc.ts, decision D13 in docs/database/MARIADB.md) to load tables into the services and write their changes back.
 *
 * - Order = creation order of the DDL, so parents come before children: inserts and updates follow it, deletes go in
 *   reverse. Foreign keys stay ON.
 * - Generated columns (principal_de_jugador_id, actual_unica, vigente_de_jugador_id, …) are never written; a model
 *   field mapped to one (descuentos.monto_final) is read-only.
 * - Types come from information_schema at runtime: DECIMAL ↔ integer cents, BOOLEAN ↔ boolean,
 *   DATETIME 'YYYY-MM-DD HH:MM:SS' ↔ 'YYYY-MM-DDTHH:MM:SS', TIME 'HH:MM:SS' ↔ 'HH:MM', JSON ↔ value.
 * api/rpc.test.ts checks the map round-trips every seeded row of every table.
 */
export interface TableMap {
  /** MockDb property. */
  key: string;
  table: string;
  /** Primary key columns. */
  pk: string[];
  /** SQL column → model field. */
  cols: Record<string, string>;
  /**
   * Rows also inserted outside the domain bridge (auth endpoints): inserted without an explicit id, so a concurrent
   * login can't collide with it. Only for tables no other table references.
   */
  dbAssignsId?: boolean;
}

